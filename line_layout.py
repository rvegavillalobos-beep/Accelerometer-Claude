def image_size() -> tuple[int, int]:
    return tuple(_D.IMAGE_SIZE)


@lru_cache(maxsize=1)
def background_uri() -> str:
    data = (Path(__file__).resolve().parent / _D.IMAGE_FILE).read_bytes()
    return "data:image/png;base64," + base64.b64encode(data).decode()


def network() -> list[list[tuple[float, float]]]:
    """Every conveyor segment of the layout as a polyline."""
    return [[(float(x), float(y)) for x, y in pts] for _a, _b, _len, pts in _D.EDGES]


def stations_table() -> pd.DataFrame:
    rows = [
        {"Key": k, "Station": name, "x": float(_D.NODES[n][0]), "y": float(_D.NODES[n][1])}
        for k, (name, n) in _D.STATIONS.items()
    ]
    return pd.DataFrame(rows).sort_values("Key").reset_index(drop=True)
