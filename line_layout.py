"""Line layout: recording file names -> sections drawn along the real conveyor path.

The layout image, the conveyor path and the station positions are fixed and embedded in the app
(line_layout_data.py and assets/line_layout.png, generated by tools/build_line_layout.py).

File-name convention:
    St430-440 [note]    section from ST 430 to ST 440 (shortest way along the conveyors)
    St989 [note]        one station (text after the number is a note, e.g. 'St540 deindex')
    St540Loop540        loop that starts and ends at ST 540 (the smallest conveyor loop through the station)
    St981-Buffer        section to a named place
"""

from __future__ import annotations

import os as _os

_LOADED_MTIME = _os.path.getmtime(__file__)  # used by app.py to detect stale modules

import base64
import heapq
import re
from functools import lru_cache
from pathlib import Path

import pandas as pd

import line_layout_data as _D

_NUM = r"\d{2,4}(?:\.\d{1,2})?"
_TOK = rf"(?:(?:ST|FT)\s*)?{_NUM}"
INF = float("inf")


# --------------------------------------------------------------------------- #
# Names
# --------------------------------------------------------------------------- #
def station_key(text, default_prefix: str = "ST") -> str | None:
    """Canonical key: 'St 540' / 'ST540' / '540' -> 'ST540'; 'FT 002' -> 'FT002'; 'Buffer' -> 'BUFFER'."""
    s = re.sub(r"\s+", "", str(text or "").upper())
    if not s:
        return None
    m = re.fullmatch(rf"(ST|FT)?({_NUM})", s)
    if m:
        return (m.group(1) or default_prefix) + m.group(2)
    s = re.sub(r"[^A-Z0-9.]", "", s)
    return s or None


def station_display(key: str | None) -> str:
    if not key:
        return ""
    if key in _D.STATIONS:
        return _D.STATIONS[key][0]
    m = re.fullmatch(rf"(ST|FT)({_NUM})", key)
    return f"{m.group(1)} {m.group(2)}" if m else key.title()


def parse_recording_name(name: str) -> dict:
    """{'From', 'To', 'Note'} from a file name such as 'St395-860.txt' or 'St540 deindex.txt'."""
    stem = re.sub(r"\s*\(\d+\)\s*$", "", str(name))  # ' (2)' added to duplicate uploads
    stem = re.sub(r"\.(txt|csv|tsv|log|dat)$", "", stem, flags=re.I).strip()
    m = re.match(rf"^\s*(?P<a>{_TOK})\s*(?:-|–|—|_|>|→|\s+to\s+)\s*(?P<b>{_TOK})(?![\d.])(?P<rest>.*)$", stem, re.I)
    if m is None:  # second end is a named place, e.g. St981-Buffer
        m = re.match(rf"^\s*(?P<a>{_TOK})\s*(?:-|–|—|>|→|\s+to\s+)\s*(?P<b>[A-Za-z][A-Za-z0-9]*)(?P<rest>.*)$", stem, re.I)
    if m is not None:
        a = station_key(m["a"])
        b = station_key(m["b"], default_prefix=a[:2] if a and a[:2] in ("ST", "FT") else "ST")
        return {"From": a, "To": b if b != a else None, "Note": m["rest"].strip(" _-")}
    m = re.match(rf"^\s*(?P<a>{_TOK})(?![\d.])(?P<rest>.*)$", stem, re.I)
    if m is not None:
        return {"From": station_key(m["a"]), "To": None, "Note": m["rest"].strip(" _-")}
    return {"From": None, "To": None, "Note": stem}


def sections_table(recordings: list[str]) -> pd.DataFrame:
    rows = []
    for rec in recordings:
        p = parse_recording_name(rec)
        rows.append(
            {
                "Recording": rec,
                "From": station_display(p["From"]),
                "To": station_display(p["To"]),
                "Via": "",
                "Note": p["Note"],
            }
        )
    return pd.DataFrame(rows, columns=["Recording", "From", "To", "Via", "Note"])


def section_keys(row) -> tuple[str | None, str | None, list[str]]:
    a = station_key(row.get("From"))
    b = station_key(row.get("To"), default_prefix=a[:2] if a and a[:2] in ("ST", "FT") else "ST")
    via = [k for k in (station_key(v) for v in re.split(r"[,;/]+", str(row.get("Via") or ""))) if k]
    return a, (None if b == a else b), via


def is_loop(row) -> bool:
    a, b, _via = section_keys(row)
    return b is None and "loop" in str(row.get("Note") or "").lower()


def known_stations() -> list[str]:
    return sorted(_D.STATIONS, key=lambda k: (k[:2] != "ST", k))


# --------------------------------------------------------------------------- #
# Conveyor graph
# --------------------------------------------------------------------------- #
@lru_cache(maxsize=1)
def _adjacency() -> dict[int, list[tuple[int, float, int]]]:
    adj: dict[int, list[tuple[int, float, int]]] = {i: [] for i in range(len(_D.NODES))}
    for k, (a, b, length, _pts) in enumerate(_D.EDGES):
        if a != b:
            adj[a].append((b, length, k))
            adj[b].append((a, length, k))
    return adj


def _shortest(src: int, dst: int, banned_edge: int | None = None) -> tuple[float, list[tuple[int, int, int]]] | None:
    adj = _adjacency()
    dist, prev, heap = {src: 0.0}, {}, [(0.0, src)]
    while heap:
        d, u = heapq.heappop(heap)
        if u == dst:
            break
        if d > dist.get(u, INF):
            continue
        for v, length, k in adj[u]:
            if k == banned_edge:
                continue
            nd = d + length
            if nd < dist.get(v, INF):
                dist[v], prev[v] = nd, (u, k)
                heapq.heappush(heap, (nd, v))
    if dst not in dist:
        return None
    seq, v = [], dst
    while v != src:
        u, k = prev[v]
        seq.append((u, v, k))
        v = u
    return dist[dst], seq[::-1]


def _polyline(seq: list[tuple[int, int, int]]) -> list[tuple[float, float]]:
    pts: list[tuple[float, float]] = []
    for u, _v, k in seq:
        a, _b, _len, e_pts = _D.EDGES[k]
        part = list(e_pts) if a == u else list(reversed(e_pts))
        pts.extend(part if not pts else part[1:])
    return [(float(x), float(y)) for x, y in pts]


def node_xy(key: str) -> tuple[float, float] | None:
    st = _D.STATIONS.get(key)
    if st is None:
        return None
    x, y = _D.NODES[st[1]]
    return float(x), float(y)


def route(keys: list[str]) -> tuple[list[tuple[float, float]], float] | None:
    """Shortest way along the conveyors through the given stations, in order."""
    nodes = [_D.STATIONS[k][1] for k in keys]
    pts: list[tuple[float, float]] = []
    total = 0.0
    for a, b in zip(nodes[:-1], nodes[1:]):
        if a == b:
            continue
        res = _shortest(a, b)
        if res is None:
            return None
        d, seq = res
        part = _polyline(seq)
        pts.extend(part if not pts else part[1:])
        total += d
    if not pts:
        pts = [_D.NODES[nodes[0]]]
    return pts, total


def loop(key: str) -> tuple[list[tuple[float, float]], float] | None:
    """Smallest conveyor loop that passes through a station."""
    s = _D.STATIONS[key][1]
    best = None
    for v, length, k in _adjacency()[s]:
        res = _shortest(v, s, banned_edge=k)
        if res is None:
            continue
        d, seq = res
        if best is None or length + d < best[0]:
            best = (length + d, [(s, v, k)] + seq)
    if best is None:
        return None
    return _polyline(best[1]), best[0]


def section_geometry(row) -> dict:
    """How one row of the sections table is drawn: kind 'route' / 'loop' / 'point', or what is missing."""
    a, b, via = section_keys(row)
    keys = [k for k in [a, *via, b] if k]
    if not keys:
        return {"kind": "unnamed", "keys": [], "missing": [], "path": [], "length": 0.0}
    missing = [k for k in keys if k not in _D.STATIONS]
    if missing:
        return {"kind": "missing", "keys": keys, "missing": missing, "path": [], "length": 0.0}
    if b is None and not via:
        if is_loop(row):
            lp = loop(a)
            if lp is not None:
                return {"kind": "loop", "keys": keys, "missing": [], "path": lp[0], "length": lp[1]}
        return {"kind": "point", "keys": keys, "missing": [], "path": [node_xy(a)], "length": 0.0}
    r = route(keys)
    if r is None:
        return {"kind": "no_path", "keys": keys, "missing": [], "path": [], "length": 0.0}
    return {"kind": "route", "keys": keys, "missing": [], "path": r[0], "length": r[1]}


def section_label(row) -> str:
    a, b, via = section_keys(row)
    if not a:
        return str(row.get("Recording", ""))
    text = station_display(a)
    if b:
        text += " → " + station_display(b)
    if via:
        text += " (via " + ", ".join(station_display(v) for v in via) + ")"
    note = str(row.get("Note") or "").strip()
    return text + (f" · {note}" if note else "")


